/**
 * 把規則說明裡的 `**強調**` 畫成粗體。
 *
 * # 為什麼強調要活在文字裡，而不是拆成 JSX
 *
 * 因為那些句子的主人是 `lib/admission.mjs` 與 `lib/star.mjs`，而它們是
 * **有測試的純函式**。測試裡有一條斷言的是「介面上必須說明放棄亦無法
 * 恢復資格」——它比對的就是那段文字。若把強調拆成 JSX 放在頁面裡，
 * 文字就分家了：規則那一側改了句子，頁面這一側的粗體會留在錯的位置上，
 * 而沒有任何測試看得到。
 *
 * 所以強調跟著句子一起走，這裡只負責把它畫出來。
 *
 * 刻意**只認 `**`**。這不是 Markdown 渲染器——支援得越多，就越可能有人
 * 把使用者輸入（例如志願的備註）餵進來，那時它就變成一個注入面。
 * 這裡的輸入永遠是程式自己寫的常數字串。
 */
export function Emph({ text }: { text: string }) {
  // split 保留奇數位的擷取群組，於是「一般、粗體、一般、粗體…」交錯。
  const parts = text.split(/\*\*(.+?)\*\*/g);
  return (
    <>
      {parts.map((part, i) =>
        i % 2 === 1 ? <strong key={i}>{part}</strong> : <span key={i}>{part}</span>,
      )}
    </>
  );
}
