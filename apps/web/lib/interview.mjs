/**
 * 第二階段的面試準備（N5）：題庫、結構回饋，以及與學習歷程的一致性。
 *
 * # 為什麼回饋只評結構
 *
 * 「這個答案好不好」是招生委員的判斷。系統給了會發生兩件事，兩件都壞：
 *
 * **一、它會是錯的。** 同一個回答，甲校覺得誠懇、乙校覺得沒有準備。
 * 各校系的甄選項目與比重差異極大（規格書 §10、A.11），而系統手上沒有
 * 任何一份評分表可以對。給出來的「這題答得不錯」是憑空的。
 *
 * **二、學生會照著改。** 這比第一件嚴重得多。他會把回答改成他以為的
 * 「正確答案」，而那個正確答案是一個沒有根據的模型偏好——結果是他
 * 進面試場時講的不是自己的話。**面試最常見的失分本來就是講稿感**，
 * 而系統會親手製造它。
 *
 * 所以這裡只回答看得出來的三件事：**有沒有回答到問題、有沒有具體例子、
 * 有沒有前後矛盾**。這三件事不需要價值判斷，而且它們的改善方向是
 * 明確的——「你沒有講到為什麼是這個系」不會讓任何人變成別人。
 *
 * # 為什麼結構回饋是確定性的，不是模型算的
 *
 * 與 `lib/grading.mjs` 同一個分工。這三件事全部可以用規則判定，而規則
 * 判定的好處在這裡特別大：**它不會偷偷開始評價內容。** 模型被要求
 * 「只評結構」時，第三輪就會寫出「你的例子很具體，展現了良好的
 * 團隊合作能力」——後半句是內容評價，而它混在結構觀察裡送出去。
 *
 * 模型在這一塊仍然有位置（追問的問題），但它走 `portfolioGuard.mjs`
 * 的同一道閘門，而且回饋的骨架在沒有模型時就已經完整。
 *
 * # 一致性檢查：面試最貴的一種失分
 *
 * 「檔案裡寫的跟口頭講的對不起來」。這在現場是致命的——委員手上就
 * 拿著那份檔案，而學生自己通常不記得三個月前寫了什麼。
 *
 * 檢查的方式刻意保守：**只比對得出「你講了一件檔案裡沒有的事」，
 * 不判斷那是不是矛盾。** 學生完全可以講檔案裡沒寫的經歷（檔案有篇幅
 * 限制），所以輸出是一個提醒而不是一個錯誤——「你提到了『機器人社』，
 * 但你的自述與素材裡沒有這幾個字。委員手上只有那份檔案，這一點你要
 * 自己接得起來。」
 *
 * 反過來的方向（檔案裡有而回答沒提）不檢查：那不是矛盾，那是取捨。
 */

