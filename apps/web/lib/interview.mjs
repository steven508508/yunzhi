/** 某一類的題目。`GENERAL` 永遠附在後面——通用題每一場都會問到。 */
export function templatesFor(fieldTag) {
  const tag = String(fieldTag ?? '').trim().toUpperCase();
  const specific = QUESTION_TEMPLATES.filter((q) => q.fieldTag === tag && tag !== 'GENERAL');
  const general = QUESTION_TEMPLATES.filter((q) => q.fieldTag === 'GENERAL');
  return [...specific, ...general];
}

