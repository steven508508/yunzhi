/**
 * 專有名詞的候選。
 *
 * 抓的是**看起來像一個東西的名字**：引號裡的、社團隊伍營隊、競賽獎項、
 * 課程專題。抓不到的就抓不到——這一項的價值在於「抓到的那幾個一定
 * 值得問」，不在於抓得全。抓太寬的話，每一次練習都跳出十個提醒，
 * 學生會直接忽略整個功能。
 */
/**
 * 名字的左界。
 *
 * **這一行是必要的，不是潔癖。** 用正規表達式往左吃固定字數的話，
 * 「最後在機器人社」會被抓成「後在機器人社」（非貪婪也一樣，因為
 * 引擎是從最左邊的位置開始試的）。於是每一次練習都跳出一個對不上的
 * 「名詞」，而那種提醒出現兩次之後學生就不看了——這個功能等於沒有。
 *
 * 所以改成從標記往左走，碰到助詞、動詞或非中文就停。
 */
const NAME_STOP = /[的了是在和與及我你他她它們這那有就也都很過到從對把被給讓做去來會要還又再並而但最後然又個位次件]/;

function nameBefore(s, endIdx, maxLen) {
  let start = endIdx;
  while (start > 0 && endIdx - start < maxLen) {
    const ch = s[start - 1];
    if (!/[一-鿿]/.test(ch) || NAME_STOP.test(ch)) break;
    start -= 1;
  }
  return s.slice(start, endIdx);
}

function claimTokens(text) {
  const s = String(text ?? '');
  const out = new Set();
  for (const m of s.matchAll(/[「『]([^」』]{2,12})[」』]/g)) out.add(m[1]);
  for (const re of [/社|隊|營|團|中心|實驗室/g, /科展|競賽|比賽|檢定|證照|專題|工作坊/g]) {
    re.lastIndex = 0;
    for (const m of s.matchAll(re)) {
      const head = nameBefore(s, m.index, 5);
      if (head) out.add(head + m[0]);
    }
  }
  // 三個字以下多半是普通名詞（「社團」「比賽」），當成名字去比對只會
  // 製造雜訊。**寧可漏抓**：抓到的每一個都要值得問。
  return [...out].filter((t) => Array.from(t).length >= 3);
}

/**
 * 面試回答與學習歷程對得起來嗎。
 *
 * @param {string} answer
 * @param {{body?: string|null}[]} essays 學生的自述與綜整心得
 * @param {{title?: string|null, note?: string|null}[]} items 素材
 * @returns {{ok: boolean, unmatched: string[], note: string}}
 *
 * **只查一個方向**：回答裡提到、而檔案裡找不到的東西。反過來不查，
 * 理由見檔頭——檔案裡有而回答沒提是取捨，不是矛盾。
 */
export function consistencyCheck(answer, essays = [], items = []) {
  const corpus = [
    ...(essays ?? []).map((e) => e?.body ?? ''),
    ...(items ?? []).map((i) => `${i?.title ?? ''} ${i?.note ?? ''}`),
  ].join('\n');
  const bareCorpus = bare(corpus);

  const unmatched = claimTokens(answer).filter((t) => !bareCorpus.includes(bare(t)));

  return {
    ok: unmatched.length === 0,
    unmatched,
    note:
      bareCorpus.length === 0
        ? '你的學習歷程裡還沒有內容，所以這一項沒有比對。等自述寫好之後再練一次，這裡才有用。'
        : unmatched.length === 0
          ? '你講到的東西，在你的檔案裡都找得到。'
          : `你提到了${unmatched.map((t) => `「${t}」`).join('、')}，但你的自述與素材裡沒有這幾個字。` +
            '這不一定有問題——檔案有篇幅限制，本來就寫不完。但**委員手上只有那份檔案**，' +
            '所以他聽到這幾個詞的時候接不上前因後果。要嘛在回答裡多給一句背景，' +
            '要嘛在檔案裡補一筆。',
  };
}

