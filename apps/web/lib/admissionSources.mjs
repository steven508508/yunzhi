/**
 * 「這一項要去哪裡查」——升學資料的查詢指引與網址推導。
 *
 * # 為什麼系統的角色是「告訴你去哪裡查」而不是「幫你查」
 *
 * 因為**禁止爬取的是機器，不是人**。規格書文件 07 §2.1 那條紅線寫的是
 * `cac.edu.tw` 全站 robots.txt 禁止自動化抓取，而學生自己打開官方網頁
 * 查一個校系的錄取標準完全沒有問題——那本來就是輔導老師會叫他做的事。
 * 校內百分比更是只有教務處有，網路上根本不存在。
 *
 * 所以系統做三件它真的做得到的事：**告訴你去哪裡查** → **把你查到的
 * 記下來（含來源與日期）** → **在上面給建議**。這個檔案是第一件。
 *
 * # 兩種網址要用完全不同的處理方式，這是本檔案的核心
 *
 * **推得出來的**（`star{民國年}`）。繁星的當年度簡章頁是
 * `www.cac.edu.tw/star115/index.php` 這種形狀，學年度換了就換一個數字。
 * 所以組得出來——但**絕不宣稱它一定有效**。網址會變（委員會改版、
 * 路徑搬家），而一個死連結比沒有連結更讓人卡住：學生點下去看到 404，
 * 他的結論是「這個系統壞了」而不是「我該從首頁進去找」。所以推出來的
 * 網址一律帶著 `caution` 與 `fallback`（委員會首頁）一起給。
 *
 * **推不出來的**（個申篩選標準一覽表）。它的路徑是混淆過的長字串，
 * 例如 114 學年度是
 * `.../CacLink/apply114/114appLy_3Hd_SieVe_QueRy_9dS4cqa1g_Kp3z/...`
 * ——那串亂碼每年重新產生（文件 07 §3.5：111 學年度起無穩定網址），
 * 推不出來也猜不到。這一類**只給首頁加導覽指示**，因為寫死一個深連結
 * 的結果是它在下一個學年度變成一個 404，而畫面上看起來一切正常。
 *
 * 這兩件事分開的方式是 `urlKind`，而且有測試釘著「推不出來的那一種
 * 永遠不會被組出一個假的深連結」——那是這個檔案唯一一種會安靜壞掉的
 * 失效方式。
 *
 * # 清單為什麼照繁星的實際時序排
 *
 * 因為學生是照時序遇到這些問題的：11 月簡章公告他才知道有哪些校系、
 * 2 月底成績出來才知道有沒有過檢定、3 月初校內推薦作業才真的要決定
 * 推哪一個。照系統結構排（「校系資料」「成績資料」「校內資料」）
 * 讀起來很整齊，但它回答不了「我現在該做什麼」——而那是學生打開
 * 這一頁的唯一理由。
 *
 * # 這個檔案不碰網路
 *
 * 一行 fetch 都沒有。網址是給人點的常數字串，不是給程式抓的目標。
 * 這一條是專案的硬規則（文件 07 §2.1），而它在程式碼上的落實方式
 * 就是：這個檔案是純資料與純字串組裝，沒有任何 I/O 可以被加進來
 * 而不被 code review 看見。
 *
 * # 每年要有人看一次的東西，只有這幾樣
 *
 * 這個模組每年都要維護，所以「哪些東西會過期」必須數得出來：
 *
 *   一、**逐年公告的統計量**。全部集中在 `lib/admission.mjs` 的
 *       `STAR_VACANCY_FACT`，而且顯示時一律走 `starVacancySentence()`
 *       ——那一支在年份對不上時會改口說「最近一次有數字的是哪一年」，
 *       而不是把舊數字掛上新年份。這個檔案裡**沒有第二個寫死的統計值**。
 *   二、**推導出來的網址**（`star{民國年}`）。它吃 `year`，所以不會過期，
 *       但委員會改版時整條規則會失效——那是 `caution` 與 `fallback`
 *       存在的理由。
 *   三、**時程的月份**（「2 月底成績公布」「3 月中放榜」）。制度性的，
 *       多年不變；真的變了是整套制度改，那時這一份清單本來就要重寫。
 *
 * 註解裡的年份（`star115`、`apply114` 那兩個例子、「111 學年度起無穩定
 * 網址」）**是歷史紀錄不是設定值**，它們說明的是「當年長成什麼樣子」，
 * 所以不隨年度更新。
 */
