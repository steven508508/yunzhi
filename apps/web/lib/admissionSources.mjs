/**
 * 依學年度**推導**出來的。可能有效，可能已經搬家。
 * 一律附 `caution` 與 `fallback`。
 */
export const URL_DERIVED = 'DERIVED';

/** 已經查證過的固定網址（首頁、機構入口）。這幾個不隨學年度變。 */
export const URL_FIXED = 'FIXED';

/**
 * **推不出來。** 只能給入口加導覽指示。
 * 這一類的 `url` 永遠是入口首頁或 null，永遠不是深連結。
 */
export const URL_NONE = 'NONE';

