// §5 查資料清單
//
// 依繁星的實際時序排。每一項都要說出三件事：
//   · 要查什麼（一句話講得完的具體項目）
//   · 去哪裡查（`where`，含網址的性質）
//   · **查到之後輸入到哪裡**（`recordAs`，對到 AdmissionReference.kind）
//
// 第三件最容易被漏掉，而漏掉的後果是這一頁變成一份書籤清單：學生查完
