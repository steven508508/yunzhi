/** 大學甄選入學委員會首頁。繁星與個申的總入口，也是所有退路的終點。 */
export const CAC_PORTAL = 'https://www.cac.edu.tw/cacportal/index.php';

/** 大考中心。級分人數累計表與五標的唯一官方來源。 */
export const CEEC = 'https://www.ceec.edu.tw/';

/** 大學招生委員會聯合會的考試與招生行事曆。 */
export const JBCRC_CALENDAR = 'https://www.jbcrc.edu.tw/calendar/';

// ═════════════════════════════════════════════════════════════════
// §3 推導
// ═════════════════════════════════════════════════════════════════

/**
 * 繁星推薦當年度的簡章頁。**推導出來的，不保證有效。**
 *
 * 形狀是 `star` 加民國學年度：115 學年度是 `star115`。
 *
 * 回傳的物件裡 `caution` 與 `fallback` 不是裝飾——呼叫端要把它們一起
 * 顯示出來。只給網址的話，學生點到一個 404 就停在那裡了，而正確的
 * 下一步（從委員會首頁進去找）他不會自己想到。
 *
 * @param {number} year 民國學年度
 */
export function starCircularUrl(year) {
  const y = Number(year);
  if (!Number.isInteger(y) || y < 100 || y > 200) {
    // 學年度不合法時**不組網址**。組出 `starNaN` 或 `star2026` 的話，
    // 學生點下去是 404，而他不會知道問題出在系統把西元年填進來了。
    return {
      url: null,
      urlKind: URL_NONE,
      label: '繁星推薦當年度簡章',
      caution: `學年度「${year}」不是民國學年度（100 至 200），所以組不出網址。`,
      fallback: CAC_PORTAL,
      fallbackLabel: '大學甄選入學委員會首頁',
    };
  }
  return {
    url: `https://www.cac.edu.tw/star${y}/index.php`,
    urlKind: URL_DERIVED,
    label: `${y} 學年度繁星推薦招生簡章`,
    caution:
      '這個網址是依學年度推出來的（star 加民國年），不是查證過的。' +
      '打不開就從委員會首頁進去找——網址會變，但首頁不會。',
    fallback: CAC_PORTAL,
    fallbackLabel: '大學甄選入學委員會首頁',
  };
}

/**
 * 個人申請的歷年篩選標準一覽表。**推不出來。**
 *
 * 路徑是混淆過的長字串（114 學年度那一串裡有 `_3Hd_SieVe_QueRy_9dS4cqa1g_Kp3z`
 * 這種每年重新產生的亂碼），而且文件 07 §3.5 明確記載 111 學年度起
 * 沒有穩定網址。
 *
 * 所以這一支**回的是首頁加導覽步驟**，而且它的回傳值裡不含任何路徑
 * 片段——測試會檢查這件事。寫死一個深連結的代價是它在下一個學年度
 * 變成 404，而那時沒有人會發現：畫面上仍然有一個看起來很正常的連結。
 */
export function sieveStandardGuide() {
  return {
    url: CAC_PORTAL,
    urlKind: URL_NONE,
    label: '個人申請歷年篩選標準一覽表',
    /** 從首頁走到那一頁的步驟。**這才是這一支真正給出的東西。** */
    navigation: ['大學甄選入學委員會首頁', '申請入學', '歷年篩選標準查詢（一覽表）'],
    caution:
      '這一頁的網址每年重新產生、而且是一串亂碼，推不出來也猜不到，' +
      '所以這裡只給入口與路徑。照上面的步驟點進去，不要指望有一個固定連結。',
  };
}

