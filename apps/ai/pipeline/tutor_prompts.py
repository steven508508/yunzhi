"""
雲端智學 — 智慧老師（引導式教學）的提示詞

# 這一組提示詞與匯入那一組的性質完全不同

匯入的提示詞要的是**準確**，錯了老師校對時看得出來。這一組要的是
**克制**，而它錯了沒有人看得出來——一段把答案講出來的回應，讀起來
比一句好的提問更像「有幫助」。學生會滿意，老師會覺得系統很聰明，
而那位學生下一次遇到同一個觀念仍然不會。

業主對現有工具的抱怨是「AI 功能不好用」。這裡的「不好用」不是慢，
是**它只是一個比較慢的解析**。所以整組提示詞只有一個目標：
讓模型問問題，不要讓它講答案。

# 這一層擋不住的事，寫在這裡免得有人以為它擋得住

提示詞是三層設限的第一層，而它是三層裡最弱的一層。學生連續說
三次「拜託直接告訴我」，模型十之八九會妥協——這不是提示詞寫得不夠
兇可以解決的，是對齊訓練讓它傾向順從使用者。真正守住的是 Node 端
`lib/tutorGuard.mjs` 的確定性閘門：它看完整段輸出，命中就重新生成。

所以這裡的措辭以「讓正常情況下的輸出品質好」為目標，不是以
「窮盡所有繞過方式」為目標。後者做不到。

# 正確答案為什麼還是放進脈絡裡

文件 03 §5.2 建議「不允許揭露時，標準答案根本不放進上下文」——
模型不知道就洩漏不了，那確實是更強的保證。這裡沒有採用，理由是
引導的品質：不知道正確答案的模型會把學生往錯的方向帶（它會自己
解一次，而它解錯的那幾題正好是學生也錯的那幾題），而「AI 把我教錯」
比「AI 講太快」嚴重得多。

代價由閘門承擔。答案放進脈絡的同時，這裡用一個明確的界線把它框起來
並反覆聲明不可複述——而**這件事的成敗不由這一層決定**。
"""

from __future__ import annotations

