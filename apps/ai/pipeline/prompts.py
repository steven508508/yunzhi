def rubric_user(text: str, expected_total: float | None) -> str:
    hint = (
        f"\n交叉驗證資訊：依試題卷所載，本題配分為 {expected_total} 分。"
        f"若你抽出的最高等第上限與此不符，請重新確認。"
        if expected_total is not None
        else ""
    )
    return f"""
<material>
{text}
</material>
{hint}

只輸出符合 RubricOut schema 的 JSON。
""".strip()


